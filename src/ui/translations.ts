export type Language = keyof typeof messages;

export type MessageKey = keyof typeof messages.fr;
// Compile-time completeness when adding a new language or message.
const complete: Record<Language, Record<MessageKey, string>> = messages;

export function translate(language: Language, key: MessageKey, values: Record<string, string | number> = {}) {
  return complete[language][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function initialLanguage(saved: string | null, browserLanguage: string): Language {
  return saved === 'fr' || saved === 'en' ? saved : browserLanguage.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

