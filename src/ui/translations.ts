/** Keep low-level codes stable while presenting plain language in the selected locale. */
export function shipExportErrorKey(code: string): MessageKey {
  if (code === 'E_DOWNLOAD') return 'exportDownloadError';
  if (code === 'E_EMPTY_CONSTRUCTION') return 'shipExportEmpty';
  if (code === 'E_CODEC_UNAVAILABLE') return 'shipExportCodec';
  if (code === 'E_PAYLOAD_CAPACITY') return 'shipExportCapacity';
  if (code === 'E_EXPORT_WORKER') return 'shipExportWorker';
  if (code === 'E_EXPORT_TIMEOUT') return 'shipExportTimeout';
  if (['E_PNG_PROFILE', 'E_EXPORT_INTEGRITY', 'E_GZIP', 'E_BINARY', 'E_TREE', 'E_NATIVE_PROFILE'].includes(code)) return 'shipExportIntegrity';
  if (['E_SCHEMA', 'E_INTEGER', 'E_TYPE', 'E_ROTATION', 'E_MIRROR', 'E_ID', 'E_LOCAL_BOUNDS', 'E_GRID', 'E_COLLISION'].includes(code)) return 'shipExportInvalid';
  return 'shipExportError';
}

/** Translate boundary errors without changing the language-independent conversion model. */
export function errorKey(message: string, fallback: 'importError' | 'conversionError'): MessageKey {
  if (message === 'empty-silhouette') return 'noBlack';
  if (/256 Mio/.test(message)) return 'bytesError';
  if (/64 millions/.test(message)) return 'pixelsError';
  if (/dimension.*(dépasse|positifs)/i.test(message)) return 'dimensionError';
  if (/animé/.test(message)) return 'animatedError';
  if (/Format non reconnu|en-tête|PNG valide/.test(message)) return 'formatError';
  if (/décoder/.test(message)) return 'decodeError';
  if (/capacités de traitement|lire les pixels/.test(message)) return 'memoryError';
  if (/dépassé.*secondes/.test(message)) return 'timeoutError';
  if (/Worker|traitement isolé|transférer|transmettre|prévisualisation/.test(message)) return 'workerError';
  return fallback;
}

export function unificationKey(status: string | undefined, detail = ''): MessageKey {
  if (status === 'empty') return 'unificationEmpty';
  if (status === 'budget-reached') return 'unificationBudget';
  if (status === 'incompatible') {
    if (detail.includes('axe impair')) return 'unificationAxis';
    if (detail.includes('petits triangles')) return 'unificationTriangles';
    return 'unificationIncompatible';
  }
  return 'unificationSearch';
}
